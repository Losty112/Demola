-- Benchmark Hospital — Postgres schema for Supabase.
-- Run once in the Supabase SQL editor (or `supabase db push`). Safe to re-run: every statement is idempotent.
--
-- Security model: the browser never talks to Supabase. The Next.js server uses the service-role key,
-- which bypasses row level security. RLS is switched on with NO policies, so the public anon key
-- (which Supabase exposes by design) can read and write nothing.

-- ---------------------------------------------------------------- core tables (used by the scoring engine)

create table if not exists sites (
  id         bigint generated by default as identity primary key,
  slug       text not null unique,
  name       text not null,
  region     text not null default '',
  kind       text not null default 'Hospital',
  created_at timestamptz not null default now()
);

create table if not exists site_snapshots (
  id           bigint generated by default as identity primary key,
  site_id      bigint not null references sites(id) on delete cascade,
  period       text not null check (period ~ '^\d{4}-Q[1-4]$'),   -- e.g. 2026-Q3, sorts lexicographically
  beds         integer not null check (beds > 0),
  occupancy    numeric(5,1) not null check (occupancy between 0 and 100),
  area_per_bed numeric(7,1) not null check (area_per_bed > 0),
  cost_per_m2  numeric(8,1) not null check (cost_per_m2 > 0),
  or_util      numeric(5,1) not null check (or_util between 0 and 100),
  space_use    numeric(5,1) not null check (space_use between 0 and 100),
  energy       numeric(7,1) not null check (energy > 0),
  travel_time  numeric(6,1) not null check (travel_time >= 0),
  source       text not null default 'manual',
  imported_at  timestamptz not null default now(),
  unique (site_id, period)
);

create table if not exists benchmark_values (
  metric_key text primary key,
  value      numeric not null,
  source     text not null default 'illustrative placeholder',
  updated_at timestamptz not null default now()
);

create table if not exists settings (
  key   text primary key,
  value numeric not null,
  note  text not null default ''
);

create table if not exists meta (
  key   text primary key,
  value text not null
);

-- ---------------------------------------------------------------- detail statistics

-- Wards / clinical departments of a site; a quarterly row per department follows.
create table if not exists departments (
  id      bigint generated by default as identity primary key,
  site_id bigint not null references sites(id) on delete cascade,
  code    text not null,
  name    text not null,
  unique (site_id, code)
);

create table if not exists department_snapshots (
  id            bigint generated by default as identity primary key,
  department_id bigint not null references departments(id) on delete cascade,
  period        text not null check (period ~ '^\d{4}-Q[1-4]$'),
  beds          integer not null check (beds > 0),
  occupancy     numeric(5,1) not null check (occupancy between 0 and 100),
  avg_los_days  numeric(5,1) not null check (avg_los_days > 0),
  admissions    integer not null check (admissions >= 0),
  bed_days      integer not null check (bed_days >= 0),
  nurse_fte     numeric(7,1) not null check (nurse_fte >= 0),
  physician_fte numeric(7,1) not null check (physician_fte >= 0),
  unique (department_id, period)
);

-- Activity per calendar month (month = first day of the month).
create table if not exists monthly_activity (
  id         bigint generated by default as identity primary key,
  site_id    bigint not null references sites(id) on delete cascade,
  month      date not null check (extract(day from month) = 1),
  admissions integer not null check (admissions >= 0),
  discharges integer not null check (discharges >= 0),
  ed_visits  integer not null check (ed_visits >= 0),
  surgeries  integer not null check (surgeries >= 0),
  bed_days   integer not null check (bed_days >= 0),
  energy_kwh bigint  not null check (energy_kwh >= 0),
  unique (site_id, month)
);

create table if not exists operating_rooms (
  id                    bigint generated by default as identity primary key,
  site_id               bigint not null references sites(id) on delete cascade,
  period                text not null check (period ~ '^\d{4}-Q[1-4]$'),
  rooms                 integer not null check (rooms > 0),
  available_hours       numeric(9,1) not null check (available_hours > 0),
  used_hours            numeric(9,1) not null check (used_hours >= 0),
  cases                 integer not null check (cases >= 0),
  cancellation_pct      numeric(4,1) not null check (cancellation_pct between 0 and 100),
  turnover_min          numeric(5,1) not null check (turnover_min >= 0),
  first_case_ontime_pct numeric(4,1) not null check (first_case_ontime_pct between 0 and 100),
  unique (site_id, period)
);

-- Quarterly facility cost split by category (amount in EUR for the quarter).
create table if not exists cost_breakdown (
  id         bigint generated by default as identity primary key,
  site_id    bigint not null references sites(id) on delete cascade,
  period     text not null check (period ~ '^\d{4}-Q[1-4]$'),
  category   text not null,
  amount_eur bigint not null check (amount_eur >= 0),
  unique (site_id, period, category)
);

-- Where a site's inpatients come from, per calendar year.
create table if not exists patient_flows (
  id             bigint generated by default as identity primary key,
  site_id        bigint not null references sites(id) on delete cascade,
  year           integer not null check (year between 2000 and 2100),
  municipality   text not null,
  patients       integer not null check (patients >= 0),
  avg_travel_min numeric(5,1) not null check (avg_travel_min >= 0),
  unique (site_id, year, municipality)
);

-- ---------------------------------------------------------------- indexes (unique constraints already cover the lookups above)
create index if not exists idx_department_snapshots_period on department_snapshots (period);
create index if not exists idx_departments_site on departments (site_id);

-- ---------------------------------------------------------------- row level security: on, no policies
alter table sites                enable row level security;
alter table site_snapshots       enable row level security;
alter table benchmark_values     enable row level security;
alter table settings             enable row level security;
alter table meta                 enable row level security;
alter table departments          enable row level security;
alter table department_snapshots enable row level security;
alter table monthly_activity     enable row level security;
alter table operating_rooms      enable row level security;
alter table cost_breakdown       enable row level security;
alter table patient_flows        enable row level security;

-- ---------------------------------------------------------------- helper for the seed script
-- Seed data uses explicit ids for sites/departments; this moves the identity sequences past them.
create or replace function reset_identity_sequences() returns void
language sql as $$
  select setval(pg_get_serial_sequence('sites', 'id'), greatest(1, coalesce((select max(id) from sites), 1)));
  select setval(pg_get_serial_sequence('departments', 'id'), greatest(1, coalesce((select max(id) from departments), 1)));
$$;
revoke all on function reset_identity_sequences() from public, anon, authenticated;
